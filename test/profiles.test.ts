import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { IsolatedClient } from './fixtures/isolated-client.ts';

test('actual Pi: Profile commands preserve the public config and reject malformed catalogs without overwriting them', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'dag-public-profile-'));
  const directory = join(root, 'agent/pi-dag-workflow');
  await mkdir(directory, { recursive: true });
  const path = join(directory, 'pi-dag-workflow-profile.json');
  const client = await IsolatedClient.start(root, 'public-profile'); t.after(() => client.close());
  await client.prompt('/agents profile reader dag-test/scripted off read');
  const saved = { profiles: [{ name: 'reader', model: { provider: 'dag-test', id: 'scripted' }, thinking: 'off', tools: ['read'] }] };
  assert.deepEqual(JSON.parse(await readFile(path, 'utf8')), saved);
  const listed = await client.prompt('/agents profiles');
  assert.ok(listed.some(record => record.method === 'notify' && String(record.message).includes('reader')));
  assert.equal(client.records.some(record => record.type === 'agent_start'), false);
  const invalid = JSON.stringify({ profiles: [{ name: 'unknown', model: { provider: 'dag-test', id: 'missing' } }] });
  await writeFile(path, invalid);
  const rejected = await client.prompt('/agents profiles');
  assert.ok(rejected.some(record => record.method === 'notify' && String(record.message).includes('Unknown model')));
  assert.equal(await readFile(path, 'utf8'), invalid);
  await writeFile(path, JSON.stringify(saved));
  const restored = await client.prompt('TEST CALL subagent_inspect {"profiles":"summary"}');
  const result = restored.find(record => record.type === 'tool_execution_end' && record.toolName === 'subagent_inspect')!.result as any;
  assert.deepEqual(result.details.profiles, saved.profiles);
  assert.equal(result.isError, undefined);
  assert.equal(client.records.some(record => record.type === 'extension_error'), false);
});
